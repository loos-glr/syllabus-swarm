def validate_theory_file(file_path: Path) -> ValidationResult:
    """Validate a single theory file based on its extension.

    Parameters
    ----------
    file_path : Path
        Path to the theory file to validate.

    Returns
    -------
    ValidationResult
        Result with pass/fail status and list of issues found.
    """
    suffix = file_path.suffix.lower()

    if suffix in (".html", ".htm"):
        return _validate_html(file_path)
    elif suffix == ".sh":
        return _validate_shell(file_path)
    elif suffix == ".md":
        return _validate_markdown(file_path)
    else:
        return ValidationResult(
            file_path=file_path,
            format_type="unknown",
            passed=True,
            issues=[
                ValidationIssue(
                    "warning",
                    f"Unknown file type '{suffix}' — no validation performed.",
                )
            ],
        )


def validate_theory_directory(theory_dir: Path) -> list[ValidationResult]:
    """Validate all theory files in a directory (non-recursive).

    Parameters
    ----------
    theory_dir : Path
        Directory containing theory files.

    Returns
    -------
    list[ValidationResult]
        One result per file found.  Empty list if directory doesn't exist.
    """
    if not theory_dir.exists() or not theory_dir.is_dir():
        return []

    results: list[ValidationResult] = []
    for file_path in sorted(theory_dir.iterdir()):
        if file_path.is_file() and not file_path.name.startswith("."):
            results.append(validate_theory_file(file_path))

    return results


def format_validation_report(results: list[ValidationResult]) -> str:
    """Format validation results as a human-readable Markdown report.

    Parameters
    ----------
    results : list[ValidationResult]
        Results from :func:`validate_theory_directory` or individual
        :func:`validate_theory_file` calls.

    Returns
    -------
    str
        Markdown-formatted report string.
    """
    if not results:
        return "*No theory files found to validate.*"

    total_errors = sum(r.error_count for r in results)
    total_warnings = sum(r.warning_count for r in results)
    total_files = len(results)
    passed_files = sum(1 for r in results if r.passed)

    lines: list[str] = [
        "## Theory File Validation Report",
        "",
        "| Metric | Count |",
        "|--------|-------|",
        f"| Files checked | {total_files} |",
        f"| Files passed | {passed_files} |",
        f"| Files with errors | {total_files - passed_files} |",
        f"| Total errors | {total_errors} |",
        f"| Total warnings | {total_warnings} |",
        "",
    ]

    if total_errors == 0 and total_warnings == 0:
        lines.append("✅ **All theory files passed validation.**")
        return "\n".join(lines)

    for result in results:
        status = "✅" if result.passed else "❌"
        lines.append(f"### {status} `{result.file_path.name}` ({result.format_type})")
        lines.append("")

        if not result.issues:
            lines.append("*No issues found.*")
            lines.append("")
            continue

        for issue in result.issues:
            icon = "🔴" if issue.severity == "error" else "🟡"
            location = f" (line {issue.line})" if issue.line else ""
            lines.append(f"- {icon} **[{issue.severity.upper()}]{location}** {issue.message}")
            if issue.snippet:
                lines.append(f"  ```js\n  {issue.snippet}\n  ```")
        lines.append("")

    return "\n".join(lines)


