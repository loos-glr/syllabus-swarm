def _validate_markdown(file_path: Path) -> ValidationResult:
    """Validate a Markdown theory file.

    Checks:
      1. Mermaid code blocks have matching opening/closing fences.
      2. At least one Mermaid diagram is present.
      3. Basic Markdown structure (has H1, has content).
    """
    result = ValidationResult(file_path=file_path, format_type="markdown", passed=True)

    try:
        content = file_path.read_text(encoding="utf-8")
    except Exception as exc:
        result.passed = False
        result.issues.append(ValidationIssue("error", f"Cannot read file: {exc}"))
        return result

    lines = content.split("\n")

    # ── Check 1: Mermaid fence matching ────────────────────────────────
    in_mermaid = False
    mermaid_start_line = 0
    mermaid_count = 0

    for i, line in enumerate(lines, start=1):
        stripped = line.strip()
        if stripped.startswith("```mermaid"):
            if in_mermaid:
                result.issues.append(
                    ValidationIssue(
                        "error",
                        f"Nested mermaid code block — missing closing ``` before line {i}.",
                        line=i,
                    )
                )
                result.passed = False
            in_mermaid = True
            mermaid_start_line = i
            mermaid_count += 1
        elif stripped == "```" and in_mermaid:
            in_mermaid = False
        elif stripped.startswith("```") and in_mermaid:
            # A different language fence inside mermaid — probably a mistake
            result.issues.append(
                ValidationIssue(
                    "error",
                    f"Found '{stripped}' inside mermaid block starting at "
                    f"line {mermaid_start_line}.  Did you forget to close "
                    f"the mermaid block with ```?",
                    line=i,
                )
            )
            result.passed = False

    if in_mermaid:
        result.issues.append(
            ValidationIssue(
                "error",
                f"Unclosed mermaid code block starting at line "
                f"{mermaid_start_line}.  Add ``` on its own line to close it.",
                line=mermaid_start_line,
            )
        )
        result.passed = False

    # ── Check 2: At least one Mermaid diagram ──────────────────────────
    if mermaid_count == 0:
        result.issues.append(
            ValidationIssue(
                "warning",
                "No Mermaid.js diagrams found.  Format C artifacts should "
                "include at least 2 mermaid code blocks.",
            )
        )

    # ── Check 3: Basic structure ───────────────────────────────────────
    has_h1 = any(line.strip().startswith("# ") for line in lines)
    if not has_h1:
        result.issues.append(
            ValidationIssue(
                "warning",
                "No H1 heading (# Title) found.  Every artifact should start with a clear title.",
            )
        )

    return result


