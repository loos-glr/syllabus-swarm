def _validate_shell(file_path: Path) -> ValidationResult:
    """Validate a shell script theory file.

    Checks:
      1. Has shebang (#!/usr/bin/env bash or #!/bin/bash).
      2. Has 'set -euo pipefail' (or equivalent).
      3. Bash syntax is valid (bash -n).
    """
    result = ValidationResult(file_path=file_path, format_type="shell", passed=True)

    try:
        content = file_path.read_text(encoding="utf-8")
    except Exception as exc:
        result.passed = False
        result.issues.append(ValidationIssue("error", f"Cannot read file: {exc}"))
        return result

    # ── Check 1: Shebang ───────────────────────────────────────────────
    first_line = content.split("\n")[0].strip() if content else ""
    if not first_line.startswith("#!"):
        result.issues.append(
            ValidationIssue(
                "error",
                "Missing shebang.  Shell scripts must start with "
                "#!/usr/bin/env bash or #!/bin/bash.",
                line=1,
            )
        )
        result.passed = False
    elif "bash" not in first_line:
        result.issues.append(
            ValidationIssue(
                "warning",
                f"Shebang '{first_line}' does not reference bash.  Expected '#!/usr/bin/env bash'.",
                line=1,
            )
        )

    # ── Check 2: Safety settings ───────────────────────────────────────
    if "set -e" not in content and "set -o errexit" not in content:
        result.issues.append(
            ValidationIssue(
                "warning",
                "Missing 'set -e' (errexit).  Without this, the script "
                "will continue after errors, which can confuse students.",
            )
        )
    if "set -u" not in content and "set -o nounset" not in content:
        result.issues.append(
            ValidationIssue(
                "warning",
                "Missing 'set -u' (nounset).  Without this, typos in "
                "variable names become silent empty strings.",
            )
        )
    if "set -o pipefail" not in content:
        result.issues.append(
            ValidationIssue(
                "warning",
                "Missing 'set -o pipefail'.  Without this, errors in "
                "piped commands are silently ignored.",
            )
        )

    # ── Check 3: Bash syntax ───────────────────────────────────────────
    try:
        proc = subprocess.run(
            ["bash", "-n", str(file_path)],
            capture_output=True,
            text=True,
            timeout=10,
        )
        if proc.returncode != 0:
            stderr = proc.stderr.strip()
            result.issues.append(
                ValidationIssue(
                    "error",
                    f"Bash syntax error: {stderr}",
                )
            )
            result.passed = False
    except FileNotFoundError:
        result.issues.append(
            ValidationIssue(
                "warning",
                "bash not available — skipping shell syntax check.",
            )
        )
    except subprocess.TimeoutExpired:
        result.issues.append(
            ValidationIssue(
                "warning",
                "Bash syntax check timed out.",
            )
        )

    return result


